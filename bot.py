def add_commands(user_client, owner_id):

    @user_client.on(events.NewMessage(outgoing=True, pattern=r"^\.help$"))
    async def cmd_help(event):
        await event.edit(
            "📖 **Commands**\n"
            "`.spam @user msg` / `.spam msg` — current chat mein spam\n"
            "`.raid <count>` — kisi message ko **reply** karein, bot usi message ka reply karke random msg <count> baar bhejega\n"
            "`.speed <sec>` — `.spam` aur `.raid` dono ke liye interval (0.01 se 10)\n"
            "`.stop` — sab kuch band\n"
            "`.ping` — latency\n"
            "`.logout` — is account se bot logout kar dega\n"
            "`.help` — yeh menu\n"
            f"⚡ speed: {spam.speed}s\n"
            f"👑 Owner ID: `{OWNER_ID}`"
        )

    @user_client.on(events.NewMessage(outgoing=True, pattern=r"^\.ping$"))
    async def cmd_ping(event):
        s = time.time()
        msg = await event.edit("🏓 ...")
        ms = round((time.time() - s) * 1000)
        await msg.edit(
            f"🏓 **Pong** `{ms}ms`\n"
            f"⚡ speed `{spam.speed}s`\n"
            f"📊 spam: {spam.total_sent} | raid: {raid.total_sent}"
        )

    @user_client.on(events.NewMessage(outgoing=True, pattern=r"^\.stop$"))
    async def cmd_stop(event):
        spam.stop()
        spam.clear()
        raid.stop()
        await event.edit("🛑 **Sab band.**")

    @user_client.on(events.NewMessage(outgoing=True, pattern=r"^\.speed(?: |$)"))
    async def cmd_speed(event):
        parts = event.text.split()
        if len(parts) < 2:
            await event.edit(f"⚠️ `.speed 0.5` (abhi {spam.speed}s, min 0.01, max 10)")
            return
        try:
            v = float(parts[1])
            if v < 0.01 or v > 10:
                await event.edit("⚠️ 0.01 – 10 seconds ke beech.")
                return
            spam.speed = v
            raid.speed = v
            await event.edit(f"⚡ Speed = `{v}s`")
        except ValueError:
            await event.edit("❌ Number sahi nahi.")

    @user_client.on(events.NewMessage(outgoing=True, pattern=r"^\.spam(?: |$)"))
    async def cmd_spam(event):
        try:
            chat = await event.get_chat()
            parts = event.text.split(maxsplit=1)
            if len(parts) < 2:
                await event.edit("⚠️ `.spam @user msg` ya `.spam msg`")
                return
            full = parts[1].strip()
            w = full.split()
            if w and w[0].startswith("@"):
                target, msg = w[0], " ".join(w[1:])
                if not msg:
                    await event.edit("⚠️ @ ke baad message likhein.")
                    return
            else:
                target, msg = None, full
            n = spam.add_loop(chat.id, target, msg)
            await event.edit(f"♾️ **Spam #{n} add hua**\n📢 {target or '(none)'}\n📝 `{msg[:50]}`")
            if not spam.running:
                asyncio.create_task(spam_engine(user_client))
        except Exception as e:
            await event.edit(f"❌ {e}")

    @user_client.on(events.NewMessage(outgoing=True, pattern=r"^\.raid(?: |$)"))
    async def cmd_raid(event):
        try:
            parts = event.text.split()
            if len(parts) < 2:
                await event.edit("⚠️ Kisi message ko **reply** karke `.raid 100` bhejein.")
                return
            count = int(parts[1])
            if count < 1:
                await event.edit("⚠️ Count kam se kam 1.")
                return

            if not event.is_reply:
                await event.edit("⚠️ Pehle kisi message ko **reply** karein, phir `.raid 100` bhejein.")
                return

            reply_msg = await event.get_reply_message()
            target = await user_client.get_entity(reply_msg.sender_id)

            if not RAID_MESSAGES:
                await event.edit("⚠️ `RAID_MESSAGES` list khaali hai.")
                return

            await event.edit(
                f"🔴 **Raid shuru**\n"
                f"🎯 {target.first_name or target.id} ke message ka reply\n"
                f"🔢 {count} messages\n"
                f"⚡ {raid.speed}s"
            )

            asyncio.create_task(
                raid_engine(user_client, event.chat_id, target, reply_msg.id, count)
            )
        except ValueError:
            await event.edit("❌ Number sahi nahi.")
        except Exception as e:
            await event.edit(f"❌ {e}")

    # ✅ NAYA: .logout command
    @user_client.on(events.NewMessage(outgoing=True, pattern=r"^\.logout$"))
    async def cmd_logout(event):
        try:
            await event.edit("🔓 **Logout ho raha hai...**")
            session_file = f"{SESSION_DIR}/user_{owner_id}.session"

            # Pehle running processes band karo
            spam.stop()
            spam.clear()
            raid.stop()

            # Telegram se logout
            try:
                await user_client.log_out()
            except Exception:
                pass

            # Session file delete karo
            try:
                if os.path.exists(session_file):
                    os.remove(session_file)
                journal = session_file + "-journal"
                if os.path.exists(journal):
                    os.remove(journal)
            except Exception as e:
                print(f"⚠️ Session delete error: {e}")

            await event.edit(
                "✅ **Logout successful!**\n\n"
                "Aapka session terminate ho gaya hai.\n"
                "Dobara login karne ke liye control bot ko `/start` bhejein."
            )
        except Exception as e:
            await event.edit(f"❌ Logout error: {e}")


