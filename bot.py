async def spam_engine(user_client):
    if spam.running:
        return
    spam.running = True
    spam.stop_flag = False
    spam.start_time = time.time()
    i = 0
    while spam.running and not spam.stop_flag:
        try:
            if not spam.loops:
                await asyncio.sleep(1)
                continue
            if i >= len(spam.loops):
                i = 0
            cur = spam.loops[i]
            final = f"{cur['target']} {cur['message']}" if cur["target"] else cur["message"]
            try:
                await user_client.send_message(cur["chat_id"], final)
                spam.total_sent += 1
                cur["count"] += 1
            except FloodWaitError as e:
                await asyncio.sleep(e.seconds)
                continue
            except Exception:
                pass
            i += 1
            await asyncio.sleep(spam.speed)
        except Exception:
            await asyncio.sleep(1)
    spam.running = False


async def raid_engine(user_client, chat_id, target, reply_to_id, count):
    if raid.running:
        return
    raid.running = True
    raid.stop_flag = False
    sent = 0
    target_name = getattr(target, "first_name", None) or str(getattr(target, "id", ""))

    while sent < count and not raid.stop_flag:
        try:
            msg = random.choice(RAID_MESSAGES)
            await user_client.send_message(
                chat_id,
                f"{target_name} {msg}".strip(),
                reply_to=reply_to_id
            )
            raid.total_sent += 1
            sent += 1
        except FloodWaitError as e:
            await asyncio.sleep(e.seconds)
        except Exception:
            pass
        await asyncio.sleep(raid.speed)
    raid.running = False


async def run_userbot(user_client, owner_id):
    try:
        me = await user_client.get_me()
        print(f"✅ Userbot online: {me.first_name} ({me.id})")
        add_commands(user_client, owner_id)
        try:
            await user_client.send_message("me", f"✅ Bot start. Owner ID: {OWNER_ID}\n`.help` dekhein.")
        except Exception:
            pass
        await user_client.run_until_disconnected()
    except Exception as e:
        print(f"❌ Userbot error: {e}")


