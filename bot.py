class SpamController:
    def __init__(self):
        self.loops = []
        self.running = False
        self.stop_flag = False
        self.speed = 1.0
        self.total_sent = 0
        self.start_time = None

    def add_loop(self, chat_id, target, message):
        self.loops.append({'chat_id': chat_id, 'target': target, 'message': message, 'count': 0})
        return len(self.loops)

    def clear(self):
        self.loops = []

    def stop(self):
        self.stop_flag = True
        self.running = False


class RaidController:
    def __init__(self):
        self.running = False
        self.stop_flag = False
        self.total_sent = 0
        self.speed = 1.0

    def stop(self):
        self.stop_flag = True
        self.running = False


